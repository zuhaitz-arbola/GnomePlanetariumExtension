def get_domain():
    with open("metadata.json", encoding="utf-8") as f:
        return json.load(f)["uuid"].split("@")[0]


def main():
    domain = get_domain()
    po_dir = os.path.join(os.getcwd(), "po")
    loc_dir = os.path.join(os.getcwd(), "locale")
    os.makedirs(po_dir, exist_ok=True)

    for lang in ["es", "eu"]:
        translations = TRANSLATION_DATA.get(lang, {})
        po_path = os.path.join(po_dir, f"{lang}.po")

        header = (
            'msgid ""\nmsgstr ""\n"Project-Id-Version: '
            + domain
            + '\\n"\n"Content-Type: text/plain; charset=UTF-8\\n"\n\n'
        )
        content = header
        for msgid, msgstr in translations.items():
            safe_id = msgid.replace('"', '\\"')
            safe_str = msgstr.replace('"', '\\"')
            content += f'msgid "{safe_id}"\nmsgstr "{safe_str}"\n\n'

        with open(po_path, "w", encoding="utf-8") as f:
            f.write(content)

        mo_path = os.path.join(loc_dir, lang, "LC_MESSAGES", domain + ".mo")
        os.makedirs(os.path.dirname(mo_path), exist_ok=True)
        subprocess.run(["msgfmt", po_path, "-o", mo_path])


if __name__ == "__main__":
    main()